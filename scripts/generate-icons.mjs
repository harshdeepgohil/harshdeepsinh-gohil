// Generates src/lib/icons.generated.ts with only the brand icons we use,
// so the full simple-icons package never reaches the client bundle.
// Run: npm run icons
import * as si from "simple-icons";
import { writeFileSync } from "node:fs";

const pick = {
  javascript: "siJavascript",
  typescript: "siTypescript",
  html: "siHtml5",
  css: "siCss",
  scss: "siSass",
  tailwind: "siTailwindcss",
  angular: "siAngular",
  dotnet: "siDotnet",
  efcore: "siNuget",
  bootstrap: "siBootstrap",
  mysql: "siMysql",
  git: "siGit",
  gitlab: "siGitlab",
  clickup: "siClickup",
  figma: "siFigma",
  npm: "siNpm",
  github: "siGithub",
  whatsapp: "siWhatsapp",
};

const out = {};
for (const [key, name] of Object.entries(pick)) {
  const icon = si[name];
  if (!icon) throw new Error(`Missing icon ${name}`);
  out[key] = { title: icon.title, hex: `#${icon.hex}`, path: icon.path };
}

writeFileSync(
  "src/lib/icons.generated.ts",
  `// AUTO-GENERATED by scripts/generate-icons.mjs — do not edit by hand.\n` +
    `// Icon paths © Simple Icons contributors (CC0).\n` +
    `export const generatedIcons = ${JSON.stringify(out, null, 2)} as const;\n`
);
console.log(`Wrote ${Object.keys(out).length} icons`);
